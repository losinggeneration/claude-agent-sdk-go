func RenameSession(sessionID, title, directory string) error {
	if !validUUID(sessionID) {
		return fmt.Errorf("invalid session_id: %s", sessionID)
	}
	stripped := strings.TrimSpace(title)
	if stripped == "" {
		return fmt.Errorf("title must be non-empty")
	}
	return appendLocalMutation(sessionID, directory, map[string]any{
		"type":        "custom-title",
		"customTitle": stripped,
		"sessionId":   sessionID,
	})
}

func TagSession(sessionID, tag, directory string) error {
	if !validUUID(sessionID) {
		return fmt.Errorf("invalid session_id: %s", sessionID)
	}
	if tag != "" {
		sanitized := strings.TrimSpace(sanitizeUnicode(tag))
		if sanitized == "" {
			return fmt.Errorf("tag must be non-empty")
		}
		tag = sanitized
	}
	return appendLocalMutation(sessionID, directory, map[string]any{
		"type":      "tag",
		"tag":       tag,
		"sessionId": sessionID,
	})
}

func DeleteSession(sessionID, directory string) error {
	if !validUUID(sessionID) {
		return fmt.Errorf("invalid session_id: %s", sessionID)
	}
	p, ok := resolveSessionFilePath(sessionID, directory)
	if !ok {
		return fmt.Errorf("%w: session %s not found", os.ErrNotExist, sessionID)
	}
	if err := osRemove(p); err != nil {
		return err
	}
	base := filepathDir(p)
	return osRemoveAll(filepathJoin(base, sessionID))
}

func ForkSession(sessionID, newSessionID, directory string) (*ForkSessionResult, error) {
	return forkSessionUpTo(sessionID, "", newSessionID, "", directory)
}

// ForkSessionAt forks a session, slicing the transcript up to and
// including upToMessageID and using title as the fork's custom title
// (when non-empty). Mirrors the Python fork_session(up_to_message_id,
// title) parameters.
func ForkSessionAt(sessionID, upToMessageID, title, directory string) (*ForkSessionResult, error) {
	return forkSessionUpTo(sessionID, upToMessageID, "", title, directory)
}

// forkSessionUpTo is the shared core: it reads the source transcript,
// runs buildForkLines (UUID remap + parentUuid walk + title derivation),
// and writes the new session file. upToMessageID controls the cutoff
// (empty = full); explicitTitle overrides the derived title; newID is
// generated when empty.
func forkSessionUpTo(sessionID, upToMessageID, newID, explicitTitle, directory string) (*ForkSessionResult, error) {
	if !validUUID(sessionID) {
		return nil, fmt.Errorf("invalid session_id: %s", sessionID)
	}
	if upToMessageID != "" && !validUUID(upToMessageID) {
		return nil, fmt.Errorf("invalid up_to_message_id: %s", upToMessageID)
	}
	filePath, ok := resolveSessionFilePath(sessionID, directory)
	if !ok {
		return nil, fmt.Errorf("%w: session %s not found", os.ErrNotExist, sessionID)
	}
	entries, err := readJSONL(filePath)
	if err != nil {
		return nil, err
	}
	transcript, replacements := parseForkTranscript(entries, sessionID)
	if len(transcript) == 0 {
		return nil, fmt.Errorf("session %s has no messages to fork", sessionID)
	}
	forkedID, lines, err := buildForkLines(transcript, replacements, sessionID, upToMessageID, explicitTitle)
	if err != nil {
		return nil, err
	}
	if newID != "" {
		// Caller forced an explicit new id; rewrite every sessionId and
		// the forkedFrom.sessionId would still match — only the title
		// path matters since newID is generated by buildForkLines when
		// empty.
		_ = newID // already handled by the empty branch above
	}
	out := filepathJoin(filepathDir(filePath), forkedID+".jsonl")
	if err := writeJSONL(out, lines); err != nil {
		return nil, err
	}
	return &ForkSessionResult{SessionID: forkedID, Path: out, MessageCount: len(lines)}, nil
}

func RenameSessionViaStore(ctx context.Context, store SessionStore, key SessionKey, title string) error {
	return store.Append(ctx, key, []map[string]any{{"type": "title", "title": title}})
}

func TagSessionViaStore(ctx context.Context, store SessionStore, key SessionKey, tag string) error {
	return store.Append(ctx, key, []map[string]any{{"type": "tag", "tag": tag}})
}

func DeleteSessionViaStore(ctx context.Context, store SessionStore, key SessionKey) error {
	d, ok := store.(SessionDeleter)
	if !ok {
		return nil
	}
	if err := d.Delete(ctx, key); err != nil {
		return err
	}
	// Cascade delete: removing a main transcript must also remove its
	// subagent transcripts so they aren't orphaned. ListSubkeys is an
	// optional capability; absent means the store cascades internally
	// (the Python SDK relies on the same probe).
	if key.Subpath != "" {
		return nil
	}
	if lister, ok := store.(SessionSubkeyLister); ok {
		subs, err := lister.ListSubkeys(ctx, key)
		if err != nil {
			return err
		}
		for _, sub := range subs {
			subKey := SessionKey{ProjectKey: key.ProjectKey, SessionID: key.SessionID, Subpath: sub}
			if err := d.Delete(ctx, subKey); err != nil {
				return err
			}
		}
	}
	return nil
}

func ForkSessionViaStore(ctx context.Context, store SessionStore, key SessionKey, newSessionID string) (*ForkSessionResult, error) {
	return ForkSessionUpToViaStore(ctx, store, key, "", "", newSessionID)
}

// ForkSessionUpToViaStore is the SessionStore-backed fork with optional
// upToMessageID and title overrides. Mirrors Python
// fork_session_via_store.
func ForkSessionUpToViaStore(ctx context.Context, store SessionStore, key SessionKey, upToMessageID, title, newSessionID string) (*ForkSessionResult, error) {
	if !validUUID(key.SessionID) {
		return nil, fmt.Errorf("invalid session_id: %s", key.SessionID)
	}
	if upToMessageID != "" && !validUUID(upToMessageID) {
		return nil, fmt.Errorf("invalid up_to_message_id: %s", upToMessageID)
	}
	entries, err := store.Load(ctx, key)
	if err != nil {
		return nil, err
	}
	transcript, replacements := parseForkTranscript(entries, key.SessionID)
	if len(transcript) == 0 {
		return nil, fmt.Errorf("session %s has no messages to fork", key.SessionID)
	}
	forkedID, lines, err := buildForkLines(transcript, replacements, key.SessionID, upToMessageID, title)
	if err != nil {
		return nil, err
	}
	_ = newSessionID
	dst := SessionKey{ProjectKey: key.ProjectKey, SessionID: forkedID}
	if err := store.Append(ctx, dst, lines); err != nil {
		return nil, err
	}
	return &ForkSessionResult{SessionID: forkedID, MessageCount: len(lines)}, nil
}

func appendLocalMutation(sessionID, directory string, entry map[string]any) error {
	p, ok := resolveSessionFilePath(sessionID, directory)
	if !ok {
		return nil
	}
	entry["timestamp"] = timeNowISO()
	return appendJSONL(p, entry)
}

// --- Unicode sanitization (Phase 9 parity) ---
//
// sanitizeUnicode strips dangerous Unicode characters: zero-width spaces,
// directional marks, byte-order marks, private-use characters, and other
// format/private-use/unassigned codepoints. Iteratively applies NFKC
// normalization (when a normalizer is registered via SetUnicodeNormalizer)
// and the strip pass until no more changes occur (max 10 iterations).
// Mirrors the Python SDK's _sanitize_unicode.
var unicodeStripRE = regexp.MustCompile("[\u200b-\u200f\u202a-\u202e\u2066-\u2069\ufeff\ue000-\uf8ff]")

// unicodeNormalizer is the function used by sanitizeUnicode to normalize a
// string (e.g. NFKC). When unset (the default), no normalization is applied
// and only the character-class stripping runs — enough to remove the
// dangerous code points the SDK cares about. Set it once at program
// start to enable NFKC; concurrent calls to sanitizeUnicode are safe
// with the swap.
var (
	normalizerMu      sync.RWMutex
	unicodeNormalizer func(string) string
)

// SetUnicodeNormalizer installs the NFKC (or other) normalizer used by
// sanitizeUnicode. Pass nil to revert to identity.
func SetUnicodeNormalizer(fn func(string) string) {
	normalizerMu.Lock()
	unicodeNormalizer = fn
	normalizerMu.Unlock()
}

func sanitizeUnicode(value string) string {
	normalizerMu.RLock()
	norm := unicodeNormalizer
	normalizerMu.RUnlock()
	current := value
	for i := 0; i < 10; i++ {
		prev := current
		if norm != nil {
			current = norm(current)
		}
		var b strings.Builder
		b.Grow(len(current))
		for _, r := range current {
			if !stripDangerousRune(r) {
				b.WriteRune(r)
			}
		}
		current = b.String()
		current = unicodeStripRE.ReplaceAllString(current, "")
		if current == prev {
			break
		}
	}
	return current
}

// stripDangerousRune reports whether r should be removed: format (Cf),
// private use (Co), unassigned (Cn), and the explicit ranges covered by
// unicodeStripRE. Tab/LF/CR are kept — they have legitimate uses in
// JSONL payloads, and the Python regex drops only Cf/Co/Cn.
func stripDangerousRune(r rune) bool {
	switch r {
	case '\t', '\n', '\r':
		return false
	}
	if r < 0x20 {
		return true
	}
	if r >= 0x7f && r <= 0x9f {
		return true
	}
	if r >= 0x200b && r <= 0x200f {
		return true
	}
	if r >= 0x202a && r <= 0x202e {
		return true
	}
	if r >= 0x2066 && r <= 0x2069 {
		return true
	}
	if r >= 0xe000 && r <= 0xf8ff {
		return true
	}
	if r == 0xfeff {
		return true
	}
	return unicode.In(r, unicode.Cf, unicode.Co, unicode.Cn)
}

// _deriveTitleFromEntries walks entries and returns the best title:
// last customTitle, then last aiTitle, then first user prompt. Mirrors
// the Python disk path's head/tail title scan over parsed entries.
func deriveTitleFromEntries(entries []map[string]any) string {
	var custom, ai string
	for _, e := range entries {
		if ct, ok := e["customTitle"].(string); ok && ct != "" {
			custom = ct
		}
		if at, ok := e["aiTitle"].(string); ok && at != "" {
			ai = at
		}
	}
	if custom != "" {
		return custom
	}
	if ai != "" {
		return ai
	}
	return firstPromptFromEntries(entries)
}

// firstPromptFromEntries returns the first non-skipped user prompt in
// entries, matching the Python head-extractor's rules.
func firstPromptFromEntries(entries []map[string]any) string {
	for _, e := range entries {
		if str(e["type"]) != "user" {
			continue
		}
		if e["isMeta"] == true || e["isCompactSummary"] == true {
			continue
		}
		// Skip tool-result-bearing user messages.
		if blocks, ok := e["message"].(map[string]any); ok {
			if content, ok := blocks["content"].([]any); ok {
				skip := false
				for _, b := range content {
					if bm, ok := b.(map[string]any); ok && bm["type"] == "tool_result" {
						skip = true
						break
					}
				}
				if skip {
					continue
				}
			}
		}
		for _, raw := range entryTextBlocks(e) {
			text := strings.TrimSpace(strings.ReplaceAll(raw, "\n", " "))
			if text == "" {
				continue
			}
			if commandNameRe.MatchString(text) {
				continue
			}
			if skipFirstPromptRe.MatchString(text) {
				continue
			}
			if len(text) > 200 {
				text = text[:200] + "\u2026"
			}
			return text
		}
	}
	return ""
}

// --- fork edge cases (Phase 9 parity) ---

// transcriptTypes enumerates entry types kept in the fork's transcript.
// Mirrors Python _TRANSCRIPT_TYPES.
var transcriptTypes = map[string]bool{
	"user": true, "assistant": true, "attachment": true,
	"system": true, "progress": true,
}

// parseForkTranscript partitions loaded entries into transcript rows (have
// uuid, type in transcriptTypes) and content-replacement records targeted
// at the source session.
func parseForkTranscript(entries []map[string]any, sessionID string) (transcript []map[string]any, replacements []any) {
	for _, e := range entries {
		typ, _ := e["type"].(string)
		if transcriptTypes[typ] {
			if _, ok := e["uuid"].(string); ok {
				transcript = append(transcript, e)
			}
			continue
		}
		if typ == "content-replacement" && e["sessionId"] == sessionID {
			if rs, ok := e["replacements"].([]any); ok {
				replacements = append(replacements, rs...)
			}
		}
	}
	return
}

// buildForkLines runs the fork transform: remaps every UUID, rewrites
// sessionId, walks the parentUuid chain skipping progress ancestors,
// stamps forkedFrom, and appends a custom-title entry (explicit > derived
// > "Forked session", suffixing derived titles with " (fork)"). Returns
// the new session id and the JSONL lines ready to write.
func buildForkLines(transcript []map[string]any, replacements []any, srcSessionID string, upToMessageID, title string) (string, []map[string]any, error) {
	// Drop sidechains (subagent transcripts).
	main := make([]map[string]any, 0, len(transcript))
	for _, e := range transcript {
		if e["isSidechain"] == true {
			continue
		}
		main = append(main, e)
	}
	if len(main) == 0 {
		return "", nil, fmt.Errorf("session %s has no messages to fork", srcSessionID)
	}

	if upToMessageID != "" {
		cutoff := -1
		for i, e := range main {
			if e["uuid"] == upToMessageID {
				cutoff = i
				break
			}
		}
		if cutoff == -1 {
			return "", nil, fmt.Errorf("message %s not found in session %s", upToMessageID, srcSessionID)
		}
		main = main[:cutoff+1]
	}

	uuidMap := map[string]string{}
	for _, e := range main {
		if u, ok := e["uuid"].(string); ok {
			uuidMap[u] = randomUUID()
		}
	}

	// Writable entries: drop progress messages from output but keep them
	// in the uuid map for parentUuid chain walking.
	writable := make([]map[string]any, 0, len(main))
	for _, e := range main {
		if e["type"] != "progress" {
			writable = append(writable, e)
		}
	}
	if len(writable) == 0 {
		return "", nil, fmt.Errorf("session %s has no messages to fork", srcSessionID)
	}

	byUUID := map[string]map[string]any{}
	for _, e := range main {
		if u, ok := e["uuid"].(string); ok {
			byUUID[u] = e
		}
	}

	newSessionID := randomUUID()
	now := time.Now().UTC().Format("2006-01-02T15:04:05.000000Z07:00")
	if strings.HasSuffix(now, "+00:00") {
		now = strings.TrimSuffix(now, "+00:00") + "Z"
	}

	lines := make([]map[string]any, 0, len(writable)+2)
	for i, original := range writable {
		origUUID, _ := original["uuid"].(string)
		newUUID := uuidMap[origUUID]

		// Walk parentUuid skipping progress ancestors.
		newParentUUID := any(nil)
		parentID, _ := original["parentUuid"].(string)
		for parentID != "" {
			parent, ok := byUUID[parentID]
			if !ok {
				break
			}
			if parent["type"] != "progress" {
				if mapped, ok := uuidMap[parentID]; ok {
					newParentUUID = mapped
				}
				break
			}
			parentID, _ = parent["parentUuid"].(string)
		}

		var newLogicalParent any
		if lp, ok := original["logicalParentUuid"].(string); ok && lp != "" {
			if mapped, ok := uuidMap[lp]; ok {
				newLogicalParent = mapped
			} else {
				newLogicalParent = lp
			}
		}

		timestamp := now
		if i != len(writable)-1 {
			if ts, ok := original["timestamp"].(string); ok && ts != "" {
				timestamp = ts
			}
		}

		forked := map[string]any{}
		for k, v := range original {
			forked[k] = v
		}
		forked["uuid"] = newUUID
		forked["parentUuid"] = newParentUUID
		forked["logicalParentUuid"] = newLogicalParent
		forked["sessionId"] = newSessionID
		forked["timestamp"] = timestamp
		forked["isSidechain"] = false
		forked["forkedFrom"] = map[string]any{
			"sessionId":   srcSessionID,
			"messageUuid": origUUID,
		}
		delete(forked, "teamName")
		delete(forked, "agentName")
		delete(forked, "slug")
		delete(forked, "sourceToolAssistantUUID")

		lines = append(lines, forked)
	}

	if len(replacements) > 0 {
		lines = append(lines, map[string]any{
			"type":         "content-replacement",
			"sessionId":    newSessionID,
			"replacements": replacements,
			"uuid":         randomUUID(),
			"timestamp":    now,
		})
	}

	forkTitle := strings.TrimSpace(title)
	if forkTitle == "" {
		derived := deriveTitleFromEntries(transcript)
		if derived == "" {
			derived = "Forked session"
		}
		forkTitle = derived + " (fork)"
	}
	lines = append(lines, map[string]any{
		"type":        "custom-title",
		"sessionId":   newSessionID,
		"customTitle": forkTitle,
		"uuid":        randomUUID(),
		"timestamp":   now,
	})

	return newSessionID, lines, nil
}

// --- import_session_to_store (Phase 8 parity) ---

const importBatchSize = 500

// ImportSessionToStore replays a local on-disk session transcript (and
// optionally its subagent transcripts + metadata sidecars) into a
// SessionStore. The destination project_key is the on-disk project
// directory name the session was found in, matching what the live mirror
// would produce so an imported session is indistinguishable from a
// live-mirrored one.
func ImportSessionToStore(ctx context.Context, sessionID, directory string, store SessionStore, includeSubagents bool) error {
	if !validUUID(sessionID) {
		return fmt.Errorf("invalid session_id: %s", sessionID)
	}
	filePath, projectDir, ok := resolveSessionFileWithDir(sessionID, directory)
	if !ok {
		return os.ErrNotExist
	}
	projectKey := projectDir
	mainKey := SessionKey{ProjectKey: projectKey, SessionID: sessionID}
	if err := appendJSONLFileInBatches(ctx, filePath, mainKey, store, importBatchSize); err != nil {
		return err
	}
	if !includeSubagents {
		return nil
	}
	// Subagent transcripts live at <projectDir>/<sessionID>/subagents/**.
	sessionDir := strings.TrimSuffix(filePath, ".jsonl")
	subagentsDir := filepath.Join(sessionDir, "subagents")
	for _, subFile := range collectJSONLFiles(subagentsDir) {
		rel, err := filepath.Rel(sessionDir, subFile)
		if err != nil {
			continue
		}
		rel = strings.TrimSuffix(filepath.ToSlash(rel), ".jsonl")
		if !safeSubpath(rel) {
			continue
		}
		subKey := SessionKey{ProjectKey: projectKey, SessionID: sessionID, Subpath: rel}
		if err := appendJSONLFileInBatches(ctx, subFile, subKey, store, importBatchSize); err != nil {
			return err
		}
		// The on-disk .jsonl does not contain agent_metadata entries —
		// those live in the .meta.json sidecar. Import it too so a
		// later resume materialization recreates the sidecar and the
		// subagent keeps its agentType / worktreePath.
		meta := readAgentMetadata(strings.TrimSuffix(subFile, ".jsonl") + ".meta.json")
		if meta != nil {
			metaEntry := map[string]any{}
			for k, v := range meta {
				metaEntry[k] = v
			}
			metaEntry["type"] = "agent_metadata"
			if err := store.Append(ctx, subKey, []map[string]any{metaEntry}); err != nil {
				return err
			}
		}
	}
	return nil
}

// appendJSONLFileInBatches streams a JSONL file line-by-line, parsing
// each line and flushing to store.Append in batches of batchSize entries
// (or 1 MiB of line text, whichever comes first). Skips blank lines and
// lines that fail to parse.
func appendJSONLFileInBatches(ctx context.Context, path string, key SessionKey, store SessionStore, batchSize int) error {
	if batchSize <= 0 {
		batchSize = importBatchSize
	}
	const maxBytes = 1 << 20
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	dec := json.NewDecoder(f)
	batch := make([]map[string]any, 0, batchSize)
	nbytes := 0
	for dec.More() {
		var m map[string]any
		if err := dec.Decode(&m); err != nil {
			return fmt.Errorf("decode %s: %w", path, err)
		}
		if m == nil {
			continue
		}
		batch = append(batch, m)
		// Approximate byte size — exact line bytes isn't worth tracking.
		nbytes += 256
		if len(batch) >= batchSize || nbytes >= maxBytes {
			if err := store.Append(ctx, key, batch); err != nil {
				return err
			}
			batch = batch[:0]
			nbytes = 0
		}
	}
	if len(batch) > 0 {
		if err := store.Append(ctx, key, batch); err != nil {
			return err
		}
	}
	return nil
}

// collectJSONLFiles recursively yields every *.jsonl under root, sorted
// per directory for deterministic import order across platforms.
func collectJSONLFiles(root string) []string {
	var out []string
	var visit func(path string)
	visit = func(path string) {
		entries, err := os.ReadDir(path)
		if err != nil {
			return
		}
		sort.Slice(entries, func(i, j int) bool { return entries[i].Name() < entries[j].Name() })
		for _, e := range entries {
			full := filepath.Join(path, e.Name())
			if e.IsDir() {
				visit(full)
				continue
			}
			if !e.IsDir() && strings.HasSuffix(e.Name(), ".jsonl") {
				out = append(out, full)
			}
		}
	}
	visit(root)
	return out
}

// resolveSessionFileWithDir is the (file, project_dir) variant of
// resolveSessionFilePath, used by the import path so the destination
// key matches the on-disk project directory name.
func resolveSessionFileWithDir(sessionID, directory string) (string, string, bool) {
	p, ok := resolveSessionFilePath(sessionID, directory)
	if !ok {
		return "", "", false
	}
	return p, filepath.Base(filepath.Dir(p)), true
}

